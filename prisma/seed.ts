async function main() {
  console.log('🌱 Seeding database...');

  // Create all symptoms first
  const symptomMap = new Map<string, string>(); // name -> id

  const allSymptoms = new Map<string, { name: string; category: string; description?: string }>();
  for (const disease of diseases) {
    for (const s of disease.symptoms) {
      if (!allSymptoms.has(s.name)) {
        allSymptoms.set(s.name, { name: s.name, category: s.category });
      }
    }
  }

  console.log(`Creating ${allSymptoms.size} symptoms...`);
  for (const [, s] of allSymptoms) {
    const symptom = await prisma.symptom.upsert({
      where: { name: s.name },
      update: {},
      create: {
        name: s.name,
        category: s.category,
        description: s.description || null,
      },
    });
    symptomMap.set(s.name, symptom.id);
  }

  // Create diseases and their symptom relationships
  console.log(`Creating ${diseases.length} diseases with symptom relationships...`);
  for (const d of diseases) {
    const disease = await prisma.disease.upsert({
      where: { name: d.name },
      update: {
        description: d.description,
        specialist: d.specialist,
        severity: d.severity,
        precautions: d.precautions,
        medications: d.medications,
        diet: d.diet,
      },
      create: {
        name: d.name,
        description: d.description,
        specialist: d.specialist,
        severity: d.severity,
        precautions: d.precautions,
        medications: d.medications,
        diet: d.diet,
      },
    });

    // Create disease-symptom relationships
    for (const s of d.symptoms) {
      const symptomId = symptomMap.get(s.name);
      if (symptomId) {
        await prisma.diseaseSymptom.upsert({
          where: {
            diseaseId_symptomId: {
              diseaseId: disease.id,
              symptomId: symptomId,
            },
          },
          update: { weight: s.weight },
          create: {
            diseaseId: disease.id,
            symptomId: symptomId,
            weight: s.weight,
          },
        });
      }
    }
  }

  // Create a demo user
  const demoUser = await prisma.user.upsert({
    where: { email: 'demo@healthpredict.com' },
    update: {},
    create: {
      email: 'demo@healthpredict.com',
      name: 'Demo User',
      password: '$2a$10$demohashedpassword1234567890abcdefghijklmnopqrstu',
      age: 25,
      gender: 'Male',
      bloodGroup: 'O+',
    },
  });

  console.log(`✅ Created demo user: ${demoUser.email}`);
  console.log(`✅ Seeded ${diseases.length} diseases, ${allSymptoms.size} symptoms`);
  console.log('🎉 Database seeding complete!');
}

main()
  .catch((e) => {
    console.error('❌ Seed error:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
